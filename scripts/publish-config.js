// Writes web/config.js from deployments/portaldot.json so the hosted dapp opens on the live registry.
//   npm run publish:config
const fs = require("fs");
const d = JSON.parse(fs.readFileSync("deployments/portaldot.json", "utf8"));
const cfg = { registry: d.registry, rpc: "https://test-evm-rpc-v3.portaldot.dev", chainId: d.chainId, network: "PortaldotV3 Testnet", symbol: "tPOTv3",
  explorer: "https://node-console.portaldot.dev/", demoCircle: d.circle, demoToken: d.token || "" };
fs.writeFileSync("web/config.js", `// Generated by scripts/publish-config.js from deployments/portaldot.json\nwindow.ESUSU_CONFIG = ${JSON.stringify(cfg, null, 2)};\n`);
console.log("wrote web/config.js for registry", d.registry);
