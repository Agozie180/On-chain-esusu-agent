// Generates web/contracts.js (ABIs + bytecode) and web/risk.js (the agent's risk grader, shared source) from build output.
const fs = require("fs");
const read = (n) => JSON.parse(fs.readFileSync(`artifacts/contracts/${n}.sol/${n}.json`, "utf8"));
const pick = (n) => { const a = read(n); return { abi: a.abi, bytecode: a.bytecode }; };
const erc20 = ["function balanceOf(address) view returns (uint256)", "function allowance(address,address) view returns (uint256)",
  "function approve(address,uint256) returns (bool)", "function decimals() view returns (uint8)", "function symbol() view returns (string)",
  "function mint(address,uint256)"];
fs.writeFileSync("web/contracts.js", `// AUTO-GENERATED by scripts/build-web.js. Do not edit.\nwindow.ESUSU = ${JSON.stringify({
  circle: pick("EsusuCircle"), vault: pick("AgentAllowance"), registry: pick("EsusuRegistry"), erc20,
})};\n`);
const src = fs.readFileSync("agent/policy.js", "utf8");
fs.writeFileSync("web/risk.js", `// AUTO-GENERATED from agent/policy.js. Same code the agent runs.\nwindow.POLICY = (function(){ const module = { exports: {} };\n${src}\nreturn module.exports; })();\n`);
console.log("wrote web/contracts.js, web/risk.js");
